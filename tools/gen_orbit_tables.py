#!/usr/bin/env python3
"""
Phase 2 — generate orbit_tables.gen.h from orbit_tables.py.

This is deliberately a one-way, idempotent generator. The Python file is the
source of truth; the generated header must never be hand-edited. A CI test
(tests/test_orbit_tables_gen.py) re-runs this generator in memory and diffs
against the checked-in header; any drift fails the build.
"""
import os
import sys
import textwrap

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, ROOT)

from orbit_tables import DENSITY_CODES  # noqa: E402

HEADER = textwrap.dedent("""\
    /* GENERATED by tools/gen_orbit_tables.py — DO NOT EDIT BY HAND.
     * Source of truth: orbit_tables.py
     */
    #ifndef ORBIT_TABLES_GEN_H_
    #define ORBIT_TABLES_GEN_H_

    """)

FOOTER = "\n#endif /* ORBIT_TABLES_GEN_H_ */\n"


def render():
    out = [HEADER]
    for density, code in DENSITY_CODES:
        out.append("#define DENSITY_%d    %d\n" % (density, code))
    out.append("\n")
    out.append("static inline unsigned int orbit_get_density_code(unsigned int density) {\n")
    out.append("    switch (density) {\n")
    for density, code in DENSITY_CODES:
        out.append("    case %d: return DENSITY_%d;\n" % (density, density))
    out.append("    default: return DENSITY_2;\n")
    out.append("    }\n")
    out.append("}\n")
    out.append(FOOTER)
    return "".join(out)


def main():
    target = os.path.join(ROOT, "orbit_tables.gen.h")
    content = render()
    with open(target, "w") as f:
        f.write(content)
    print("wrote %s (%d bytes)" % (target, len(content)))


if __name__ == "__main__":
    main()
